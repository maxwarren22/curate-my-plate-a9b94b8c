CREATE OR REPLACE FUNCTION "public"."match_recipe"("query_embedding" "public"."vector", "match_threshold" double precision, "match_count" integer) RETURNS TABLE("id" "uuid", "title" "text", "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  SELECT
    r.id,
    r.title,
    1 - (r.embedding <=> query_embedding) AS similarity
  FROM public.recipes AS r
  WHERE 1 - (r.embedding <=> query_embedding) > match_threshold
  ORDER BY similarity DESC
  LIMIT match_count;
$$;


